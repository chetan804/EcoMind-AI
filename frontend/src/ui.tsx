export function StatCard({
  label,
  value,
  sub,
  icon,
  tone = 'brand',
}: {
  label: string
  value: ReactNode
  sub?: ReactNode
  icon?: ReactNode
  tone?: 'brand' | 'info' | 'warn' | 'danger' | 'purple'
}) {
  const tones: Record<string, string> = {
    brand: 'text-emerald-400 bg-emerald-500/10',
    info: 'text-sky-400 bg-sky-500/10',
    warn: 'text-amber-400 bg-amber-500/10',
    danger: 'text-rose-400 bg-rose-500/10',
    purple: 'text-violet-300 bg-violet-500/10',
  }
  return (
    <div className="panel panel-hover p-4">
      <div className="flex items-center justify-between">
        <span className="text-[11px] font-semibold uppercase tracking-wider text-[var(--color-faint)]">{label}</span>
        {icon && <div className={clsx('rounded-lg p-1.5', tones[tone])}>{icon}</div>}
      </div>
      <div className="mt-2 text-2xl font-bold tracking-tight text-[var(--color-ink)]">{value}</div>
      {sub && <div className="mt-1 text-xs text-[var(--color-mute)]">{sub}</div>}
    </div>
  )
}

