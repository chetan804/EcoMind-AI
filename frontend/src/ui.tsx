/* EcoMind-AI design system: reusable presentational components. */

import { type ReactNode, useEffect } from 'react'
import { clsx } from 'clsx'
import { Loader2, X } from 'lucide-react'
import { statusColor, humanize } from './lib/format'

export function Spinner({ className }: { className?: string }) {
  return <Loader2 className={clsx('animate-spin', className)} size={18} />
}

export function Badge({
  children,
  tone = 'neutral',
  className,
}: {
  children: ReactNode
  tone?: 'neutral' | 'brand' | 'warn' | 'danger' | 'info' | 'purple'
  className?: string
}) {
  const tones: Record<string, string> = {
    neutral: 'text-slate-300 bg-slate-500/10 border-slate-500/25',
    brand: 'text-emerald-400 bg-emerald-500/10 border-emerald-500/25',
    warn: 'text-amber-400 bg-amber-500/10 border-amber-500/25',
    danger: 'text-rose-400 bg-rose-500/10 border-rose-500/25',
    info: 'text-sky-400 bg-sky-500/10 border-sky-500/25',
    purple: 'text-violet-300 bg-violet-500/10 border-violet-500/25',
  }
  return <span className={clsx('chip border', tones[tone], className)}>{children}</span>
}

export function StatusBadge({ status }: { status: string }) {
  return <span className={clsx('chip border', statusColor(status))}>{humanize(status)}</span>
}

