"""Declarative base, naming convention and mixins shared by every module's models.

Conventions (see docs/database/schema-overview.md):
- Primary keys are UUIDs generated by PostgreSQL (``gen_random_uuid()``).
- Every table has timezone-aware ``created_at`` and ``updated_at``.
- Constraints and indexes use the deterministic names below so Alembic diffs stay stable.
- Quantities carry the unit in the column name (``weight_kg``) or in an explicit unit column.
- Enumerations are stored as VARCHAR with a CHECK constraint (``enum_column``), which keeps
  migrations simple (no PostgreSQL ENUM type alterations).
"""

from __future__ import annotations

import datetime as dt
import decimal
import enum
import uuid
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    MetaData,
    Numeric,
    Table,
    event,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, MappedColumn, Mapper, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


class TimestampMixin:
    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


def enum_column(enum_cls: type[enum.Enum]) -> Enum:
    """Store a Python enum as VARCHAR constrained by one CHECK named ``ck_<table>_<column>_valid``.

    The type-level constraint of ``sqlalchemy.Enum`` is disabled (``create_constraint=False``)
    because Alembic renders it twice; the table-level CHECK is attached by the listener below.
    """
    return Enum(
        enum_cls,
        native_enum=False,
        create_constraint=False,
        length=max(len(m.value) for m in enum_cls) + 8,
        values_callable=lambda cls: [m.value for m in cls],
        validate_strings=True,
    )


@event.listens_for(Base, "instrument_class", propagate=True)
def _attach_enum_checks(mapper: Mapper[Any], class_: type) -> None:
    """Add one CHECK per enum column when a model class is mapped (runs once per table)."""
    table = mapper.local_table
    if not isinstance(table, Table):
        return
    existing = {constraint.name for constraint in table.constraints}
    for column in list(table.columns):
        column_type = column.type
        if not isinstance(column_type, Enum) or column_type.native_enum:
            continue
        name = f"{column.name}_valid"
        if name in existing:
            continue
        values = ", ".join(f"'{value}'" for value in column_type.enums)
        table.append_constraint(CheckConstraint(text(f"{column.name} IN ({values})"), name=name))


class CreatedAtMixin:
    """For append-only tables (history, ledger, audit): rows are never updated."""

    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )


class GeoPointMixin:
    """Optional WGS84 point stored as two columns (PostGIS is not required yet).

    Add ``*geo_point_constraints()`` to the table's ``__table_args__``.
    """

    latitude: Mapped[decimal.Decimal | None] = mapped_column(Numeric(9, 6))
    longitude: Mapped[decimal.Decimal | None] = mapped_column(Numeric(9, 6))


def geo_point_constraints() -> tuple[CheckConstraint, ...]:
    return (
        CheckConstraint("latitude BETWEEN -90 AND 90", name="latitude_range"),
        CheckConstraint("longitude BETWEEN -180 AND 180", name="longitude_range"),
        CheckConstraint("(latitude IS NULL) = (longitude IS NULL)", name="geo_point_complete"),
    )


def fk_uuid(
    target: str,
    *,
    nullable: bool = False,
    ondelete: str | None = None,
    index: bool = True,
) -> MappedColumn[uuid.UUID]:
    """UUID foreign key column. Default ``ondelete`` is RESTRICT (no silent cascades)."""
    return mapped_column(
        UUID(as_uuid=True),
        ForeignKey(target, ondelete=ondelete),
        nullable=nullable,
        index=index,
    )
