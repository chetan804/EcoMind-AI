"""Knowledge base, assistant transcripts and support tickets. Owned by ``support``."""

from __future__ import annotations

import datetime as dt
import uuid
from typing import Any

from sqlalchemy import Boolean, Computed, DateTime, Index, String, Text
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import (
    Base,
    CreatedAtMixin,
    TimestampMixin,
    UUIDPrimaryKeyMixin,
    enum_column,
    fk_uuid,
)
from app.modules.support.constants import MessageKind, MessageRole, TicketStatus

# The vector is generated by PostgreSQL from the two text columns, so it can never drift from them.
_SEARCH_VECTOR = (
    "setweight(to_tsvector('english', coalesce(title, '')), 'A') || "
    "setweight(to_tsvector('english', coalesce(body, '')), 'B') || "
    "setweight(to_tsvector('english', coalesce(keywords, '')), 'C')"
)


class KnowledgeArticle(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """A help article. ``source`` says where its content comes from (nothing is anonymous)."""

    __tablename__ = "knowledge_articles"
    __table_args__ = (
        Index("ix_knowledge_articles_search_vector", "search_vector", postgresql_using="gin"),
    )

    slug: Mapped[str] = mapped_column(String(100), nullable=False, unique=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    category: Mapped[str] = mapped_column(String(60), nullable=False, index=True)
    # Words people use for this topic that the article itself does not (synonyms, local terms).
    keywords: Mapped[str] = mapped_column(Text, nullable=False, server_default="")
    source: Mapped[str] = mapped_column(String(200), nullable=False)
    published: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default="true", index=True
    )
    created_by_id: Mapped[uuid.UUID | None] = fk_uuid("users.id", nullable=True)
    updated_by_id: Mapped[uuid.UUID | None] = fk_uuid("users.id", nullable=True)
    search_vector: Mapped[Any] = mapped_column(TSVECTOR, Computed(_SEARCH_VECTOR, persisted=True))


class AssistantConversation(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __tablename__ = "assistant_conversations"

    user_id: Mapped[uuid.UUID] = fk_uuid("users.id", ondelete="CASCADE")


class AssistantMessage(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    __tablename__ = "assistant_messages"

    conversation_id: Mapped[uuid.UUID] = fk_uuid("assistant_conversations.id", ondelete="CASCADE")
    role: Mapped[MessageRole] = mapped_column(enum_column(MessageRole), nullable=False)
    kind: Mapped[MessageKind] = mapped_column(enum_column(MessageKind), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    # [{"kind": "article", "id": "...", "title": "..."}]; never holds personal data.
    sources: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB, nullable=False, server_default="[]"
    )
    helpful: Mapped[bool | None] = mapped_column(Boolean)


class SupportTicket(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __tablename__ = "support_tickets"

    user_id: Mapped[uuid.UUID] = fk_uuid("users.id")
    subject: Mapped[str] = mapped_column(String(200), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[TicketStatus] = mapped_column(
        enum_column(TicketStatus),
        nullable=False,
        index=True,
        server_default=TicketStatus.OPEN.value,
    )
    assignee_id: Mapped[uuid.UUID | None] = fk_uuid("users.id", nullable=True)
    # Set only when the person chose to share the assistant conversation with the support team.
    shared_conversation_id: Mapped[uuid.UUID | None] = fk_uuid(
        "assistant_conversations.id", nullable=True, ondelete="SET NULL"
    )
    resolved_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))


class SupportTicketReply(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    __tablename__ = "support_ticket_replies"

    ticket_id: Mapped[uuid.UUID] = fk_uuid("support_tickets.id", ondelete="CASCADE")
    author_id: Mapped[uuid.UUID] = fk_uuid("users.id")
    is_staff: Mapped[bool] = mapped_column(Boolean, nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
