#!/usr/bin/env python3
"""Create `.env.demo-mail`: DEMONSTRATION e-mail settings for the optional Mailpit container.

Mailpit is a mail catcher: it accepts every message the app sends and shows it in a web inbox
(http://localhost:8025). Nothing is delivered to the Internet, so no real SMTP provider is needed
for a supervised demo. The user name and password are generated here (never committed; the file is
git-ignored) and are only the credentials between the backend and the Mailpit container.

Changing the credentials later:
  * regenerate them:   python3 scripts/setup/init_demo_mail.py --rotate
  * or edit `.env.demo-mail` by hand (keep MAILPIT_SMTP_AUTH equal to SMTP_USERNAME:SMTP_PASSWORD)
  * for a real provider, put EMAIL_BACKEND=smtp and the provider's SMTP_* values in `.env`
    (SMTP_SECURITY=starttls) and stop passing `.env.demo-mail`; see docs/operations/account-recovery.md.

Run via `make demo-mail-env`; start the stack with `make demo-mail-up`. Local use only: the backend
refuses SMTP_SECURITY=none in production.
"""

from __future__ import annotations

import argparse
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / ".env.demo-mail"


def render(username: str, password: str) -> str:
    return (
        "# DEMONSTRATION e-mail settings (generated by scripts/setup/init_demo_mail.py).\n"
        "# Messages go to the Mailpit container only: http://localhost:8025\n"
        "EMAIL_BACKEND=smtp\n"
        "EMAIL_FROM=\"EcoMind AI Demo <no-reply@example.org>\"\n"
        "APP_BASE_URL=http://localhost:5173\n"
        "SMTP_HOST=mailpit\n"
        "SMTP_PORT=1025\n"
        "SMTP_SECURITY=none\n"
        f"SMTP_USERNAME={username}\n"
        f"SMTP_PASSWORD={password}\n"
        f"MAILPIT_SMTP_AUTH={username}:{password}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rotate", action="store_true", help="replace existing credentials")
    args = parser.parse_args(argv)
    if TARGET.exists() and not args.rotate:
        print(f"kept     {TARGET.name} (already exists; use --rotate to replace the credentials)")
        return 0
    TARGET.write_text(render("demo-mailer", secrets.token_urlsafe(18)))
    TARGET.chmod(0o600)
    print(f"{'rotated' if args.rotate else 'created'}  {TARGET.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
